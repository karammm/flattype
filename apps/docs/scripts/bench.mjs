// Measures size and decode speed on the shared fixtures and writes guide/benchmarks.md. In CI this runs on
// the GitHub Actions machine that builds the site, so the published numbers are reproducible.
import { cpus } from "node:os";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";
import { decode as untoon, encode as toon } from "@toon-format/toon";
import { decode, encode } from "@flattype/core";
import { fixtures } from "../../../fixtures/index.mjs";

const docs = join(dirname(fileURLToPath(import.meta.url)), "..");
const bytes = (s) => Buffer.byteLength(s);
const gz = (s) => gzipSync(s, { level: 9 }).length;
const n = (x) => x.toLocaleString("en-US");
const pct = (a, b) => {
  const p = Math.round((1 - a / b) * 100);
  return p === 0 ? "0%" : `${p > 0 ? "−" : "+"}${Math.abs(p)}%`;
};
function ms(fn) {
  for (let i = 0; i < 30; i++) fn();
  const times = [];
  for (let r = 0; r < 7; r++) {
    const t = performance.now();
    for (let i = 0; i < 50; i++) fn();
    times.push((performance.now() - t) / 50);
  }
  times.sort((a, b) => a - b);
  return times[3]; // median
}

const size = ["| Payload | JSON | TOON | **Flat Notation** | vs JSON | JSON gzip | Flat gzip |", "| --- | ---: | ---: | ---: | ---: | ---: | ---: |"];
const speed = ["| Payload | `JSON.parse` | TOON `decode` | **FlatType `decode`** | FlatType `encode` |", "| --- | ---: | ---: | ---: | ---: |"];
for (const [name, value] of Object.entries(fixtures)) {
  const json = JSON.stringify(value);
  const t = toon(value);
  const f = encode(value);
  size.push(`| ${name} | ${n(bytes(json))} B | ${n(bytes(t))} B | **${n(bytes(f))} B** | ${pct(bytes(f), bytes(json))} | ${n(gz(json))} B | ${n(gz(f))} B |`);
  speed.push(`| ${name} | ${ms(() => JSON.parse(json)).toFixed(3)} ms | ${ms(() => untoon(t)).toFixed(3)} ms | **${ms(() => decode(f)).toFixed(3)} ms** | ${ms(() => encode(value)).toFixed(3)} ms |`);
}

const page = `<!-- Generated by scripts/bench.mjs. -->

# Benchmarks

Measured on ${cpus()[0]?.model.trim() ?? "unknown CPU"}, Node ${process.versions.node}, when this site was built (${new Date().toISOString().slice(0, 10)}). The fixtures are in [\`fixtures/index.mjs\`](https://github.com/karammm/flattype/blob/main/fixtures/index.mjs). Run \`pnpm compare\` to measure on your machine.

## Size

${size.join("\n")}

## Speed

The median of 7 runs of 50 iterations each.

${speed.join("\n")}

## What these numbers mean

- **The savings come from lists of objects.** Keys are written once per table instead of once per row, and nested fields go into the header. A single small object is about the size of its JSON.
- **Lists whose objects have different keys** (the contacts, the activity feed and the mixed events) use Flat Notation 1.1: tables with optional fields such as \`phone?\`, and \`[+]\` items for what can't be a table. Before v1.14 they were written with an index on every line, larger than JSON and twice its size after gzip.
- **Gzip removes most of JSON's repetition,** so over a compressed connection the difference is small. The big wins are where text isn't compressed: LLM prompts and tool results (billed per token), logs, caches and local storage.
- **\`JSON.parse\` is native code** and stays faster. FlatType's decoder is plain TypeScript and runs in time linear in the input size, which the [hardening tests](/guide/security) check on every push.
- **TOON** is the [Token-Oriented Object Notation](https://github.com/toon-format/toon) reference implementation, measured with the same fixtures. It doesn't flatten nested objects into table headers, so on the list payloads here it comes out larger than JSON.
`;
writeFileSync(join(docs, "guide", "benchmarks.md"), page);
console.log("Wrote guide/benchmarks.md");
